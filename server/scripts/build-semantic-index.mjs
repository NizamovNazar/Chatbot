import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import '../src/config.js';
import {sqlPrimeKnowledgeFiles,sqlSyncKnowledgeFiles} from '../src/postgresStore.js';
import {atomicJsonWrite,readJsonStrict} from '../src/storage.js';
import { enrichDoc } from '../src/knowledgeMetadata.js';
import { buildSemanticIndex, createSemanticSearch } from '../src/semantic.js';
const folder=path.resolve(process.cwd(),'data');
await sqlPrimeKnowledgeFiles(folder);
const docsPath=path.join(folder,'docs.json'),output=path.join(folder,'semantic_index.json');
if(!fs.existsSync(docsPath))throw new Error('docs.json missing; run knowledge v4 migration first');
const docs=JSON.parse(fs.readFileSync(docsPath,'utf8')).map(enrichDoc).filter(d=>d&&d.quality>=.28&&!d.menuLike);
const seen=new Set(), unique=docs.filter(d=>!seen.has(d.fingerprint)&&seen.add(d.fingerprint));
console.log(`Building offline LSA embeddings for ${unique.length} text fragments (no internet/API required)...`);
const start=Date.now();
const result=buildSemanticIndex(unique);
if(!createSemanticSearch(result,unique))throw new Error('Semantic index self-check failed');
atomicJsonWrite(output,result);
const metaPath=path.join(folder,'docs_meta.json');
atomicJsonWrite(metaPath,{...readJsonStrict(metaPath,{}),knowledge_migrated_at:new Date().toISOString()});
await sqlSyncKnowledgeFiles(folder);
console.log(`Saved ${output} (${(fs.statSync(output).size/1024/1024).toFixed(2)} MiB); ${result.dimensions} latent dimensions; ${(Date.now()-start)/1000}s`);
